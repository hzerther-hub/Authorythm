def set_language(lang: str) -> None:
    global _current
    lang = lang if lang in T else "zh"
    changed = lang != _current
    _current = lang
    if changed:
        for fn in list(_LISTENERS):
            try:
                fn(lang)
            except Exception:  # noqa: BLE001 —— 单个监听器出错不阻断其它
                pass


